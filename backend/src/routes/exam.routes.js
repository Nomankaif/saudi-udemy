import { Router } from "express";
import multer from "multer";
import path from "node:path";
import * as controller from "../controllers/exam.controller.js";
import { previewImport, commitImport, downloadTemplate } from "../controllers/import.controller.js";
import { requireAuth, requireAdmin, requirePermission } from "../middleware/auth.middleware.js";
import { asyncHandler as wrap } from "../utils/async-handler.js";
import { ApiError } from "../utils/api-error.js";
import { listFeedback, myFeedback, saveFeedback } from "../controllers/feedback.controller.js";
const router = Router();
const admin = permission => [requireAuth, requireAdmin, requirePermission(permission)];
const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 15 * 1024 * 1024 }, fileFilter: (req, file, done) => done([".xlsx", ".csv", ".docx", ".pdf", ".json"].includes(path.extname(file.originalname).toLowerCase()) ? null : new ApiError(400, "Use XLSX, CSV, DOCX, PDF or JSON"), true) });
router.get("/", wrap(controller.listPublicExams));
router.get("/admin/all", ...admin("exams.view"), wrap(controller.listAdminExams));
router.get("/templates/:format", ...admin(["questions.view", "questions.import"]), wrap(downloadTemplate));
router.get("/admin/:id", ...admin("exams.view"), wrap(controller.getAdminExam));
router.get("/:id/admin/questions", ...admin("questions.view"), wrap(controller.listAdminQuestions));
router.post("/", ...admin("exams.create"), wrap(controller.createExam));
router.patch("/:id", ...admin("exams.edit"), wrap(controller.updateExam));
router.delete("/:id", ...admin("exams.edit"), wrap(controller.deleteExam));
router.post("/:id/publish", ...admin("exams.edit"), wrap(controller.publishExam));
router.post("/:id/unpublish", ...admin("exams.edit"), wrap(controller.unpublishExam));
router.post("/:id/questions", ...admin("questions.create"), wrap(controller.addQuestion));
router.patch("/:id/questions/bulk-access", ...admin("questions.edit"), wrap(controller.bulkAccess));
router.patch("/:id/questions/:questionId", ...admin("questions.edit"), wrap(controller.updateQuestion));
router.delete("/:id/questions/:questionId", ...admin("questions.edit"), wrap(controller.deleteQuestion));
router.post("/:id/import/preview", ...admin("questions.import"), upload.single("file"), wrap(previewImport));
router.post("/:id/import/commit", ...admin("questions.import"), wrap(commitImport));
router.get("/:id/availability", requireAuth, wrap(controller.getAvailability));
router.get("/:slug", wrap(controller.getExamBySlug));
router.get("/:id/feedback", wrap(listFeedback));
router.get("/:id/feedback/mine", requireAuth, wrap(myFeedback));
router.put("/:id/feedback/mine", requireAuth, wrap(saveFeedback));
export default router;

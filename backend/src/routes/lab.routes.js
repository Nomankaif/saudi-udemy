import { Router } from "express";
import * as c from "../controllers/lab.controller.js";
import { requireAuth, requireAdmin, requirePermission } from "../middleware/auth.middleware.js";
import { asyncHandler as wrap } from "../utils/async-handler.js";
const router = Router();
const admin = [requireAuth, requireAdmin, requirePermission("exams.edit")];
router.get("/", wrap(c.list));
router.get("/admin/all", ...admin, wrap(c.adminList));
router.post("/admin/import", ...admin, wrap(c.importTemplates));
router.post("/admin/import-simulations", ...admin, wrap(c.importSimulationTemplates));
router.post("/admin", ...admin, wrap(c.save));
router.get("/admin/:id", ...admin, wrap(c.adminGet));
router.put("/admin/:id", ...admin, wrap(c.save));
router.post("/admin/:id/publish", ...admin, wrap(c.publish));
router.post("/admin/:id/preview", ...admin, wrap(c.preview));
router.post("/admin/:id/validate", ...admin, wrap(c.validateSolutions));
router.post("/admin/:id/unpublish", ...admin, wrap(c.unpublish));
router.delete("/admin/:id", ...admin, wrap(c.archive));
router.get("/attempts", requireAuth, wrap(c.history));
router.get("/attempts/:attemptId", requireAuth, wrap(c.getAttempt));
router.post("/attempts/:attemptId/command", requireAuth, wrap(c.command));
router.post("/attempts/:attemptId/complete", requireAuth, wrap(c.complete));
router.post("/attempts/:attemptId/check", requireAuth, wrap(c.check));
router.post("/attempts/:attemptId/solution", requireAuth, wrap(c.solution));
router.post("/attempts/:attemptId/reset", requireAuth, wrap(c.reset));
router.post("/attempts/:attemptId/submit", requireAuth, wrap(c.submit));
router.get("/:id/availability", requireAuth, wrap(c.availability));
router.post("/:id/start", requireAuth, wrap(c.start));
export default router;
